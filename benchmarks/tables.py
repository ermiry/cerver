#!/usr/bin/env python3
# writes src/cerver/json/tables.c, the powers of five of the numbers of the JSON of cerver
# each power is the 128 most significant bits of 5^q, as two words of 64 bits, for the q from FIRST to LAST:
# - a power that is not negative is cut to its 128 bits (the ones up to 5^55 are exact);
# - a negative one is 2^b / 5^-q plus one, for the b that leaves its first bit set; the ones below
#   5^-27 are computed with more bits and cut again, which leaves them cut as the positive ones
# it is the table of the algorithm of Eisel and Lemire to read a double, and the writer takes
# from it the ceiling of each power of ten (the next integer of the ones that are cut)
# usage: python3 benchmarks/tables.py > src/cerver/json/tables.c

FIRST = -342
LAST = 324

WORD_BITS = 64
POWER_BITS = 2 * WORD_BITS

# the negative powers from this one have the bits of their product with a word of 64 bits
ROUNDED_FIRST = -27

def positive_power (exponent):

	value = 5 ** exponent

	while value < (1 << (POWER_BITS - 1)):
		value <<= 1

	while value >= (1 << POWER_BITS):
		value >>= 1

	return value

def negative_power (exponent):

	power = 5 ** -exponent

	# 2^(bits - 1) < power < 2^bits: a power of five is never one of two
	bits = power.bit_length ()

	if exponent >= ROUNDED_FIRST:
		return ((1 << (bits + POWER_BITS - 1)) // power) + 1

	value = ((1 << ((2 * bits) + POWER_BITS)) // power) + 1
	while value >= (1 << POWER_BITS):
		value >>= 1

	# the writer needs to know how each power was rounded: these ones are cut
	if value != ((1 << (bits + POWER_BITS - 1)) // power):
		raise ValueError ("the power %d is not cut" % exponent)

	return value

def power_words (exponent):

	value = positive_power (exponent) if exponent >= 0 else negative_power (exponent)

	if not ((1 << (POWER_BITS - 1)) <= value < (1 << POWER_BITS)):
		raise ValueError ("the power %d does not have %d bits" % (exponent, POWER_BITS))

	return value >> WORD_BITS, value & ((1 << WORD_BITS) - 1)

def main ():

	print ("// generated by benchmarks/tables.py, never edited by hand: the 128 most significant")
	print ("// bits of each power of five, from 5^%d to 5^%d, the high word and the low one" % (FIRST, LAST))
	print ()
	print ("#include <stdint.h>")
	print ()
	print ("#include \"cerver/types/types.h\"")
	print ()
	print ("#include \"cerver/json/internal.h\"")
	print ()
	print ("const u64 json_number_powers[JSON_NUMBER_POWERS_SIZE][2] = {")

	for exponent in range (FIRST, LAST + 1):
		high, low = power_words (exponent)
		print (
			"\t{ UINT64_C (0x%016X), UINT64_C (0x%016X) }%s"
			% (high, low, "," if exponent < LAST else "")
		)

	print ("};")

if __name__ == "__main__":
	main ()
